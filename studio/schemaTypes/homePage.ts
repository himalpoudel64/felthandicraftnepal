import { defineArrayMember, defineField, defineType } from "sanity";

const titledItem = (name: string, titleLabel: string) =>
  defineArrayMember({
    type: "object",
    name,
    fields: [
      defineField({
        name: "title",
        title: titleLabel,
        type: "string",
        validation: (rule) => rule.required(),
      }),
      defineField({
        name: "text",
        title: "Text",
        type: "text",
        rows: 3,
        validation: (rule) => rule.required(),
      }),
    ],
    preview: { select: { title: "title", subtitle: "text" } },
  });

